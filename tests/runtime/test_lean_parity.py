def feed(ind, bar_fed):
    for _t, o, h, lo, c, v in BARS:
        if bar_fed:
            ind.update_bar(None, h, lo, c, v, o)
        else:
            ind.update(None, c)
    return ind.value


@pytest.mark.parametrize("name", sorted(CASES))
def test_matches_lean(name):
    expected = REF["values"].get(name, {}).get("value")
    assert expected is not None, f"no LEAN reference captured for {name}"
    make, bar_fed = CASES[name]
    got = feed(make(), bar_fed)
    assert got == pytest.approx(expected, rel=TOL, abs=1e-6), (
        f"{name}: LEAN {expected}, ours {got}")


@pytest.mark.parametrize("name", sorted(SUB_CASES))
def test_sub_series_match_lean(name):
    make, bar_fed, subs = SUB_CASES[name]
    ind = make()
    for _t, o, h, lo, c, v in BARS:
        if bar_fed:
            ind.update_bar(None, h, lo, c, v, o)
        else:
            ind.update(None, c)
    for key, read in subs.items():
        expected = REF["values"].get(name, {}).get(key)
        if expected is None:
            continue
        assert read(ind) == pytest.approx(expected, rel=TOL, abs=1e-6), (
            f"{name}.{key}: LEAN {expected}, ours {read(ind)}")


def test_the_reference_covers_what_we_claim():
    """A guard: if someone adds an indicator to CASES with no LEAN value,
    the parametrised test above would silently pass nothing."""
    missing = [n for n in CASES
               if REF["values"].get(n, {}).get("value") is None]
    assert missing == [], f"no LEAN reference for: {missing}"


def test_known_divergences_are_still_divergent():
    """If one of these starts matching, it was fixed — take it off the list
    and put it under test. A stale exemption is how a fixed bug goes back to
    being untested."""
    assert KNOWN_DIFFERENT == {}, (
        "exemptions exist but the check for them was removed; re-add it")
