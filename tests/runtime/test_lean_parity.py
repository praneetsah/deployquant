"""Indicator parity against REAL LEAN.

`lean_reference.json` is generated by tools/lean_reference.py inside the
quantconnect/lean image: the same 60-bar series fed to LEAN's own indicators,
with the resulting values recorded. Regenerate with:

    docker run --rm -v $PWD/tools:/t --entrypoint bash quantconnect/lean:latest \
      -c "pip install -q clr_loader pythonnet && cd /Lean/Launcher/bin/Debug \
          && python /t/lean_reference.py"

This is the difference between "we implemented the textbook definition" and
"we match LEAN". It has already earned its keep: it caught MomentumPercent
returning a fraction where LEAN returns a percent (100x), TriangularMovingAverage
splitting an even period wrongly, and OnBalanceVolume not seeding with the
first bar's volume. None of those are visible by reading a definition.

TOLERANCE: LEAN computes in C# `decimal` (base-10, 28 digits); we compute in
float64, so values drift in the 5th significant figure over 60 bars — worst
for the triple-smoothed and accumulating ones (Trix, NATR, ChaikinMoneyFlow
all land at ~1.5e-4).

2e-4 relative is set to DISCRIMINATE, not to pass. The smallest real bug this
file caught was TriangularMovingAverage at 3.8e-3 — a 19x margin — and the
rest were far larger: OnBalanceVolume 3.2%, AbsolutePriceOscillator 28%,
MomentumPercent 100x. Tighter than this fails on arithmetic rather than
logic, and a test that cries wolf gets muted.
"""
